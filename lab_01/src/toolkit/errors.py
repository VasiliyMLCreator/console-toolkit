class GeneralApplicationErrorClass(Exception):
    """Общий класс ошибок, которые программа умеет объяснить пользователю.

    От него наследуются ошибки калькулятора и конвертера. Также используется
    для ошибки сохранения истории. Позволяет CLI обработать эти ситуации
    одним общим обработчиком и вывести понятное сообщение.
    """


class GeneralErrorClassOfCalculatorModule(GeneralApplicationErrorClass):
    """Объединяет ошибки, относящиеся к калькулятору.

    Наследуется от общего класса ошибок приложения. Нужен, чтобы при
    необходимости отдельно обрабатывать ошибки этого модуля, например
    неверную запись математического выражения.
    """


class GeneralErrorClassOfConverterModule(GeneralApplicationErrorClass):
    """Объединяет ошибки, относящиеся к переводу единиц измерения.

    Наследуется от общего класса ошибок приложения. Его дочерние классы
    позволяют различать неверные числа, неизвестные единицы,
    несовместимые группы и недопустимую температуру.
    """


class ErrorInCorrectnessOfNumericExpression(GeneralErrorClassOfCalculatorModule):
    """Сообщает, что математическое выражение нельзя вычислить.

    Используется для пустой строки, неверных символов, пропущенных чисел,
    неправильных скобок и других нарушений записи. Также обозначает
    ошибки вычисления Decimal и слишком глубокую вложенность выражения.
    """


class ErrorInCorrectnessOfNumericValue(GeneralErrorClassOfConverterModule):
    """Сообщает о недопустимом числовом значении в конвертере.

    Возникает, если значение нельзя прочитать как число, оно бесконечно
    или равно NaN. Также используется, если при вычислении или переводе
    результата во float возникает ошибка или переполнение.
    """


class ErrorInCorrectnessOfUnit(GeneralErrorClassOfConverterModule):
    """Сообщает о неизвестной единице или неверной таблице единиц.

    Возникает, если название не найдено или передано не строкой.
    Также используется, если конфигурационный файл нельзя прочитать
    или в нём отсутствуют правильные данные для конвертации.
    """


class ErrorInCompatibilityOfUnits(GeneralErrorClassOfConverterModule):
    """Сообщает о попытке перевести единицы из разных групп.

    Например, длину в метрах нельзя перевести в массу в килограммах.
    Это отдельный вид ошибки конвертера, чтобы отличать несовместимые
    единицы от неизвестных названий.
    """


class ErrorInTemperatureBelowAbsoluteZero(GeneralErrorClassOfConverterModule):
    """Сообщает о температуре ниже допустимого физического предела.

    Для стандартной таблицы предел равен −273.15 градуса Цельсия,
    −459.67 градуса Фаренгейта или 0 кельвинов. Конвертер вызывает
    эту ошибку до выполнения перевода такой температуры.
    """
